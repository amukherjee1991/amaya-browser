"""Packet-level backstop: a TUN "sinkhole" that is the namespace's default route.

Inside the private network namespace the only interfaces are ``lo`` and a TUN
device owned by this process.  IPv4 and IPv6 default routes point into the TUN,
so *any* packet the browser tries to send to a non-loopback address -- direct
TCP connects, QUIC/HTTP3, DoH to a hard-coded IP, STUN/WebRTC, mDNS, DNS to a
hard-coded resolver, pingsender at shutdown -- ends up here, where we parse the
IP/TCP/UDP headers, record the destination and drop the packet.  Nothing ever
reaches a real network, and the browser's own sandbox is untouched (no ptrace,
no seccomp interference).
"""

import fcntl
import ipaddress
import os
import select
import struct
import subprocess
import threading

TUNSETIFF = 0x400454CA
IFF_TUN = 0x0001
IFF_NO_PI = 0x1000

TUN_ADDR4 = "198.19.255.254"
TUN_ADDR6 = "fd00:a3a9::1"

PROTO_NAMES = {1: "icmp", 6: "tcp", 17: "udp", 58: "icmpv6", 132: "sctp"}
_IGNORED_PROTOS = {2, 58}  # IGMP, ICMPv6 (ND/MLD/RS noise generated by the kernel)
_V6_EXT = {0, 43, 44, 60}  # hop-by-hop, routing, fragment, dest-opts


def _qname(payload):
    """Best-effort QNAME from a DNS query payload (for direct-DNS packets)."""
    try:
        labels, pos = [], 12
        while payload[pos]:
            n = payload[pos]
            labels.append(payload[pos + 1:pos + 1 + n].decode("ascii", "replace"))
            pos += 1 + n
        return ".".join(labels).lower() or None
    except IndexError:
        return None


def parse_packet(pkt):
    """Parse a raw IPv4/IPv6 packet.

    Returns dict(dst, proto, sport, dport, syn, qname) or None for packets
    that are not outbound application traffic (kernel ND/MLD/IGMP noise,
    non-initial fragments, garbage).
    """
    if not pkt:
        return None
    ver = pkt[0] >> 4
    if ver == 4:
        if len(pkt) < 20:
            return None
        ihl = (pkt[0] & 0x0F) * 4
        proto = pkt[9]
        frag_off = struct.unpack("!H", pkt[6:8])[0] & 0x1FFF
        if frag_off:
            return None
        dst = str(ipaddress.IPv4Address(pkt[16:20]))
        l4 = pkt[ihl:]
    elif ver == 6:
        if len(pkt) < 40:
            return None
        proto = pkt[6]
        dst_addr = ipaddress.IPv6Address(pkt[24:40])
        if dst_addr.is_multicast and proto == 58:
            return None
        dst = str(dst_addr)
        off = 40
        while proto in _V6_EXT and len(pkt) >= off + 8:
            if proto == 44 and (struct.unpack("!H", pkt[off + 2:off + 4])[0] & 0xFFF8):
                return None  # non-initial fragment
            nxt = pkt[off]
            off += 8 if proto == 44 else (pkt[off + 1] + 1) * 8
            proto = nxt
        l4 = pkt[off:]
    else:
        return None
    if proto in _IGNORED_PROTOS:
        return None
    res = {"dst": dst, "proto": PROTO_NAMES.get(proto, str(proto)),
           "sport": None, "dport": None, "syn": False, "qname": None}
    if proto in (6, 17, 132) and len(l4) >= 4:
        res["sport"], res["dport"] = struct.unpack("!HH", l4[:4])
    if proto == 6 and len(l4) >= 14:
        flags = l4[13]
        res["syn"] = bool(flags & 0x02) and not flags & 0x10
    if proto == 17 and res["dport"] in (53, 5353) and len(l4) > 8:
        res["qname"] = _qname(l4[8:])
    return res


def open_tun(name):
    fd = os.open("/dev/net/tun", os.O_RDWR)
    try:
        fcntl.ioctl(fd, TUNSETIFF, struct.pack("16sH", name.encode(), IFF_TUN | IFF_NO_PI))
    except OSError:
        os.close(fd)
        raise
    return fd


def configure_namespace(tun_name):
    """Bring up lo and route everything else into the TUN (needs ns-root)."""
    cmds = [
        ["ip", "link", "set", "lo", "up"],
        ["ip", "addr", "add", TUN_ADDR4 + "/32", "dev", tun_name],
        ["ip", "-6", "addr", "add", TUN_ADDR6 + "/128", "dev", tun_name, "nodad"],
        ["ip", "link", "set", tun_name, "up"],
        ["ip", "route", "add", "default", "dev", tun_name],
        ["ip", "-6", "route", "add", "default", "dev", tun_name],
    ]
    for c in cmds:
        r = subprocess.run(c, capture_output=True, text=True)
        if r.returncode != 0:
            raise RuntimeError("%s failed: %s" % (" ".join(c), r.stderr.strip()))


class Sinkhole:
    def __init__(self, log, pool, tun_name="amaya-sink0"):
        self.log, self.pool, self.name = log, pool, tun_name
        self.fd = open_tun(tun_name)
        self._seen = set()
        self._stop = False
        self.packets = 0

    def handle(self, pkt):
        p = parse_packet(pkt)
        if p is None:
            return None
        self.packets += 1
        key = (p["proto"], p["dst"], p["dport"], p["sport"])
        if key in self._seen:
            return None
        self._seen.add(key)
        host = p["dst"]
        detail = {"ip": p["dst"]}
        if self.pool is not None and self.pool.contains(p["dst"]):
            name = self.pool.host_for(p["dst"])
            if name:
                host = name
                detail["resolved_via_stub"] = True
        if p["qname"]:
            detail["dns_qname"] = p["qname"]
        if p["proto"] == "tcp":
            detail["syn"] = p["syn"]
        return self.log.record("sinkhole", host, p["dport"], p["proto"], **detail)

    def _loop(self):
        while not self._stop:
            r, _, _ = select.select([self.fd], [], [], 0.5)
            if not r:
                continue
            try:
                pkt = os.read(self.fd, 65535)
            except OSError:
                return
            try:
                self.handle(pkt)
            except Exception as e:  # never let one odd packet kill capture
                self.log.note("sinkhole-parse-error", error=repr(e))

    def start(self):
        threading.Thread(target=self._loop, name="sinkhole", daemon=True).start()
        return self

    def stop(self):
        self._stop = True
