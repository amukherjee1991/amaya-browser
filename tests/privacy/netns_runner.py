"""Runs INSIDE the private user+net+mount+pid namespace created by harness.py.

  1. route everything non-loopback into the TUN sinkhole (sinkhole.py);
  2. start the recording DNS stub on 127.0.0.1:53 and point resolv.conf /
     nsswitch.conf at it, hide host sockets that resolve or proxy on our
     behalf (nscd, systemd-resolved varlink, avahi, D-Bus);
  3. start the blocking logging proxy (logproxy.py);
  4. for each scenario: fresh profile + HOME, launch the browser as the real
     user (dropuser.py), idle / drive it, shut it down, kill leftovers;
  5. write status.json (events are streamed to events.jsonl as they happen).

usage: python3 netns_runner.py CONFIG.json
"""

import json
import os
import signal
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from dnsstub import DnsStub, FakeIPPool  # noqa: E402
from events import EventLog  # noqa: E402
from logproxy import LoggingProxy  # noqa: E402
import sinkhole  # noqa: E402

# Directories holding host-side sockets that would resolve names or make
# connections *outside* our namespace on the browser's behalf.
HIDE_DIRS = ["/run/nscd", "/var/run/nscd", "/run/systemd/resolve",
             "/run/avahi-daemon", "/run/dbus", "/var/run/dbus"]


def progress(msg):
    sys.stderr.write("[runner] %s\n" % msg)
    sys.stderr.flush()


def mount(*args):
    r = subprocess.run(["mount"] + list(args), capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("mount %s: %s" % (" ".join(args), r.stderr.strip()))


def isolate_filesystem(workdir, hide_runtime_uid):
    """Make name resolution go only to our stub; hide host resolver sockets."""
    hidden = []
    dirs = list(HIDE_DIRS)
    if hide_runtime_uid is not None:
        dirs.append("/run/user/%d" % hide_runtime_uid)
    for d in dirs:
        if os.path.isdir(d) and not os.path.islink(d):
            mount("-t", "tmpfs", "-o", "mode=0755,size=64k", "tmpfs", d)
            hidden.append(d)
    resolv = "nameserver 127.0.0.1\noptions attempts:2 timeout:2\n"
    ns_lines = []
    try:
        with open("/etc/nsswitch.conf") as f:
            for line in f:
                if line.split(":")[0].strip() == "hosts":
                    continue
                ns_lines.append(line)
    except OSError:
        pass
    ns_lines.append("hosts: files dns\n")
    for target, content in (("/etc/resolv.conf", resolv),
                            ("/etc/nsswitch.conf", "".join(ns_lines))):
        real = os.path.realpath(target)
        src = os.path.join(workdir, os.path.basename(target))
        with open(src, "w") as f:
            f.write(content)
        if os.path.exists(real) and not any(real.startswith(h + "/") for h in hidden):
            mount("--bind", src, real)
        else:
            # Symlink into a hidden (tmpfs) dir or dangling: create the file there.
            d = os.path.dirname(real)
            if not any(real.startswith(h + "/") for h in hidden):
                mount("-t", "tmpfs", "-o", "mode=0755,size=64k", "tmpfs", d)
                hidden.append(d)
            with open(real, "w") as f:
                f.write(content)
    return hidden


def user_js(proxy_port, marionette):
    prefs = {}
    if proxy_port:
        prefs.update({
            "network.proxy.type": 1,
            "network.proxy.http": "127.0.0.1",
            "network.proxy.http_port": proxy_port,
            "network.proxy.ssl": "127.0.0.1",
            "network.proxy.ssl_port": proxy_port,
            "network.proxy.share_proxy_settings": True,
            "network.proxy.socks": "",
            "network.proxy.socks_remote_dns": True,
            "network.proxy.no_proxies_on": "",
            "network.proxy.allow_hijacking_localhost": True,
            "network.proxy.failover_direct": False,
            "network.proxy.allow_bypass": False,
        })
    if marionette:
        # The remote agent would otherwise apply its "recommended" automation
        # prefs, which switch off updates, telemetry, Safe Browsing, Remote
        # Settings... -- exactly what we want to measure.
        prefs["remote.prefs.recommended"] = False
    lines = ["// Generated by tests/privacy (idle-traffic test). Proxy/automation only.\n"]
    for k, v in prefs.items():
        lines.append("user_pref(%s, %s);\n" % (json.dumps(k), json.dumps(v)))
    return "".join(lines)


def browser_env(cfg, scen_dir, scenario):
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"),
           "LANG": cfg.get("lang") or "C.UTF-8"}
    for sub in ("home", "cache", "config", "data", "runtime", "tmp"):
        os.makedirs(os.path.join(scen_dir, sub), mode=0o700, exist_ok=True)
    env.update({
        "HOME": os.path.join(scen_dir, "home"),
        "XDG_CACHE_HOME": os.path.join(scen_dir, "cache"),
        "XDG_CONFIG_HOME": os.path.join(scen_dir, "config"),
        "XDG_DATA_HOME": os.path.join(scen_dir, "data"),
        "XDG_RUNTIME_DIR": os.path.join(scen_dir, "runtime"),
        "TMPDIR": os.path.join(scen_dir, "tmp"),
    })
    if cfg["headful"]:
        for k in ("DISPLAY", "WAYLAND_DISPLAY", "XAUTHORITY", "XDG_RUNTIME_DIR"):
            if cfg["host_env"].get(k):
                env[k] = cfg["host_env"][k]
    else:
        env["MOZ_HEADLESS"] = "1"
    if scenario == "newtab":
        # Lets Marionette run chrome JS so the new tab is opened exactly like
        # Ctrl+T (BrowserCommands.openTab); content-only WebDriver may not
        # navigate to about:newtab.  Has no effect without -marionette.
        env["MOZ_REMOTE_ALLOW_SYSTEM_ACCESS"] = "1"
    return env


def list_ns_processes():
    me = os.getpid()
    out = []
    for p in os.listdir("/proc"):
        if p.isdigit() and int(p) != me:
            out.append(int(p))
    return out


CONTENT_COMMS = ("Web Content", "Isolated Web Co", "WebExtensions", "Privileged Cont",
                 "file:// Content", "Isolated Servic", "Prealloc")


def process_info(pid):
    try:
        with open("/proc/%d/comm" % pid) as f:
            comm = f.read().strip()
        status = {}
        with open("/proc/%d/status" % pid) as f:
            for line in f:
                k, _, v = line.partition(":")
                status[k] = v.strip()
        userns = os.readlink("/proc/%d/ns/user" % pid)
        pidns = os.readlink("/proc/%d/ns/pid" % pid)
    except OSError:
        return None
    return {"pid": pid, "comm": comm, "ppid": int(status.get("PPid", 0)),
            "seccomp": status.get("Seccomp"), "userns": userns, "pidns": pidns}


def sandbox_snapshot(browser_pid):
    """Evidence that the browser's own sandbox is active (not enforced here)."""
    procs = [i for i in map(process_info, list_ns_processes()) if i]
    parent = next((p for p in procs if p["pid"] == browser_pid), None)
    out = {"processes": len(procs), "browser_seen": parent is not None,
           "child_processes": []}
    for c in procs:
        if c is parent:
            continue
        out["child_processes"].append({
            "comm": c["comm"], "seccomp_mode": c["seccomp"],
            "own_userns": bool(parent and c["userns"] != parent["userns"]),
            "own_pidns": bool(parent and c["pidns"] != parent["pidns"]),
        })
    content = [c for c in out["child_processes"] if c["comm"].startswith(CONTENT_COMMS)]
    out["content_processes"] = len(content)
    out["content_seccomp_filtered"] = sum(1 for c in content if c["seccomp_mode"] == "2")
    return out


def kill_all(sig):
    for pid in list_ns_processes():
        try:
            os.kill(pid, sig)
        except OSError:
            pass


def reap():
    try:
        while os.waitpid(-1, os.WNOHANG)[0] > 0:
            pass
    except ChildProcessError:
        pass


NEWTAB_JS = ("const w = Services.wm.getMostRecentWindow('navigator:browser');"
             " w.BrowserCommands.openTab(); return w.gBrowser.tabs.length;")
TABINFO_JS = ("const w = Services.wm.getMostRecentWindow('navigator:browser');"
              " return w.gBrowser.tabs.length + ' tabs, selected ' + w.gBrowser.currentURI.spec;")
BLANK_JS = ("const w = Services.wm.getMostRecentWindow('navigator:browser');"
            " w.openTrustedLinkIn('about:blank', 'current'); return true;")


def drive_newtab(log, deadline_s, status):
    from marionette import Marionette
    actions = status.setdefault("actions", [])
    m = None
    step = "connect"
    try:
        m = Marionette(timeout=min(90, deadline_s))
        m.sock.settimeout(20)
        step = "new session"
        m.command("WebDriver:NewSession", {"capabilities": {}})
        actions.append("marionette session")
        time.sleep(5)
        # Everything runs as chrome JS, i.e. the same code paths as the user
        # pressing Ctrl+T and then loading a URL.  Content-context WebDriver
        # commands hang on the new about:newtab tab in headless mode.
        step = "set chrome context"
        m.command("Marionette:SetContext", {"value": "chrome"})
        step = "open new tab (BrowserCommands.openTab)"
        m.command("WebDriver:ExecuteScript", {"script": NEWTAB_JS, "args": []})
        log.note("newtab-opened")
        time.sleep(3)
        r = m.command("WebDriver:ExecuteScript", {"script": TABINFO_JS, "args": []})
        actions.append("opened new tab via BrowserCommands.openTab (%s)"
                       % (r.get("value") if isinstance(r, dict) else r))
        time.sleep(12)
        step = "load about:blank in the new tab"
        m.command("WebDriver:ExecuteScript", {"script": BLANK_JS, "args": []})
        actions.append("loaded about:blank in the new tab")
        log.note("about-blank-loaded")
        time.sleep(2)
        step = "end session"
        m.command("WebDriver:DeleteSession")
    except Exception as e:  # report, but keep idling: traffic so far is still valid
        status["error"] = "newtab driver failed at %r: %r" % (step, e)
        log.note("newtab-driver-error", step=step, error=repr(e)[:300])
    finally:
        if m is not None:
            m.close()  # frees the session so the clean quit can start a new one


def request_quit(proc, use_marionette, log):
    """Ask the browser to quit like a user would (runs shutdown code paths)."""
    if use_marionette:
        from marionette import Marionette
        try:
            m = Marionette(timeout=10)
            m.command("WebDriver:NewSession", {"capabilities": {}})
            try:
                m.command("Marionette:Quit", {"flags": ["eAttemptQuit"]})
            except Exception:
                pass  # the connection drops while the browser exits
            m.close()
            return "marionette"
        except Exception as e:
            log.note("marionette-quit-failed", error=repr(e))
    proc.send_signal(signal.SIGTERM)  # Firefox exits abruptly on SIGTERM
    return "sigterm"


def run_session(cfg, log, scenario, cmd, env, scen_dir, use_marionette, sess, stage):
    """Launch once, idle for the duration, quit, capture shutdown; fills ``sess``."""
    logf = open(os.path.join(scen_dir, "browser.log"), "ab")
    progress("scenario %s (%s): launching %s for %ss"
             % (scenario, stage, cfg["binary"], cfg["duration"]))
    log.set_stage(stage)
    proc = subprocess.Popen(cmd, env=env, stdout=logf, stderr=subprocess.STDOUT,
                            cwd=scen_dir, start_new_session=True)
    sess["pid"] = proc.pid
    driver = None
    if scenario == "newtab":
        import threading
        driver = threading.Thread(target=drive_newtab,
                                  args=(log, cfg["duration"], sess), daemon=True)
        driver.start()
    start = time.monotonic()
    snap_at = min(30, cfg["duration"] / 2)
    exited_early = None
    while time.monotonic() - start < cfg["duration"]:
        if proc.poll() is not None:
            exited_early = round(time.monotonic() - start, 1)
            break
        if "sandbox" not in sess and time.monotonic() - start >= snap_at:
            sess["sandbox"] = sandbox_snapshot(proc.pid)
        time.sleep(0.5)
    sess["alive_at_end"] = exited_early is None
    sess["clean_exit"] = False
    if exited_early is not None:
        sess["exited_after_s"] = exited_early
        sess["exit_code"] = proc.returncode
        progress("browser exited early after %ss (code %s)" % (exited_early, proc.returncode))
    log.set_stage(stage + "-shutdown" if stage != "run" else "shutdown")
    if proc.poll() is None:
        progress("scenario %s (%s): idle period over, shutting down (grace %ss)"
                 % (scenario, stage, cfg["shutdown_grace"]))
        if driver:
            driver.join(timeout=30)  # Marionette serves one client at a time
        sess["quit_via"] = request_quit(proc, use_marionette, log)
        try:
            proc.wait(timeout=max(cfg["shutdown_grace"], 30))
            sess["clean_exit"] = sess["quit_via"] == "marionette"
        except subprocess.TimeoutExpired:
            proc.send_signal(signal.SIGTERM)
        # pingsender and friends may outlive the parent; give them the grace too.
        end = time.monotonic() + cfg["shutdown_grace"]
        while time.monotonic() < end and list_ns_processes():
            reap()
            time.sleep(0.5)
    kill_all(signal.SIGKILL)
    time.sleep(0.5)
    reap()
    if driver:
        driver.join(timeout=1)
    logf.close()


def run_scenario(cfg, log, scenario, proxy_port):
    """idle / newtab: one session on a fresh profile.  restart: the same fresh
    profile launched twice -- the first session queues pings (e.g. telemetry
    waits for the data-policy notice) that only go out on the next launch."""
    scen_dir = os.path.join(cfg["workdir"], scenario)
    profile = os.path.join(scen_dir, "profile")
    os.makedirs(profile, mode=0o700)
    use_marionette = cfg["quit"] == "marionette" or scenario == "newtab"
    if proxy_port or use_marionette:
        with open(os.path.join(profile, "user.js"), "w") as f:
            f.write(user_js(proxy_port, use_marionette))
    env = browser_env(cfg, scen_dir, scenario)
    argv = [cfg["binary"], "-profile", profile, "-no-remote"]
    if use_marionette:
        argv.append("-marionette")
    cmd = [sys.executable, os.path.join(HERE, "dropuser.py"),
           str(cfg["uid"]), str(cfg["gid"]), "--"] + argv
    status = {"name": scenario, "argv": argv, "duration_s": cfg["duration"], "sessions": []}
    log.start_clock(scenario)
    stages = ["run", "relaunch"] if scenario == "restart" else ["run"]
    for stage in stages:
        sess = {"stage": stage}
        status["sessions"].append(sess)
        run_session(cfg, log, scenario, cmd, env, scen_dir, use_marionette, sess, stage)
        if not sess["alive_at_end"]:
            break
    first = status["sessions"][0]
    for k in ("sandbox", "actions", "exited_after_s", "exit_code"):
        if k in first:
            status[k] = first[k]
    errs = [s["error"] for s in status["sessions"] if s.get("error")]
    if errs:
        status["error"] = "; ".join(errs)
    status["alive_at_end"] = all(s["alive_at_end"] for s in status["sessions"]) and \
        len(status["sessions"]) == len(stages)
    status["clean_exit"] = all(s["clean_exit"] for s in status["sessions"])
    status["quit_via"] = ",".join(s.get("quit_via", "-") for s in status["sessions"])
    status["profile_created"] = os.path.exists(os.path.join(profile, "compatibility.ini"))
    return status


def main(cfg_path):
    with open(cfg_path) as f:
        cfg = json.load(f)
    status = {"ok": False, "layers": [], "errors": [], "scenarios": []}
    status_path = os.path.join(cfg["workdir"], "status.json")
    log = EventLog(os.path.join(cfg["workdir"], "events.jsonl"))

    def write_status():
        with open(status_path, "w") as f:
            json.dump(status, f, indent=2)

    try:
        if os.getuid() != 0:
            raise RuntimeError("runner must be uid 0 inside its user namespace")
        pool = FakeIPPool()
        if cfg["sinkhole"]:
            sink = sinkhole.Sinkhole(log, pool)
            sinkhole.configure_namespace(sink.name)
            sink.start()
            status["layers"].append("sinkhole")
        else:
            subprocess.run(["ip", "link", "set", "lo", "up"], check=True)
        DnsStub(log, pool).start()
        status["layers"].append("dns")
        status["hidden_dirs"] = isolate_filesystem(
            cfg["workdir"], None if cfg["headful"] else cfg["uid"])
        proxy_port = None
        if cfg["proxy"]:
            proxy = LoggingProxy(log).start()
            proxy_port = proxy.port
            status["layers"].append("proxy")
        status["proxy_port"] = proxy_port
        write_status()
        for scenario in cfg["scenarios"]:
            status["scenarios"].append(run_scenario(cfg, log, scenario, proxy_port))
            write_status()
        status["ok"] = True
    except Exception as e:
        status["errors"].append("%s: %s" % (type(e).__name__, e))
        progress("ERROR: %s" % e)
    finally:
        log.close()
        write_status()
    return 0 if status["ok"] else 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
