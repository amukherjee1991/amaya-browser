#!/usr/bin/env python3
"""Generate ui/tokens.css from ui/design/tokens.json.

Usage: ui/tools/gen-tokens.py            (writes ui/tokens.css)
       ui/tools/gen-tokens.py --check    (exit 1 if tokens.css is stale)
"""
import json
import sys
from pathlib import Path

UI = Path(__file__).resolve().parent.parent

MOTION = [
    ("ease-out", "cubic-bezier(0.23, 1, 0.32, 1)"),
    ("dur-hover", "120ms"),
    ("dur-popover", "180ms"),
    ("dur-sidebar", "200ms"),
    # Glance scrim (design README: 45%) and the split-view outer inset (layout-pane-gap).
    ("scrim", "rgba(10, 14, 12, 0.45)"),
    ("split-inset", "8px"),
]


def render(tokens: dict) -> str:
    common, light, dark = [], [], []
    for fam, val in tokens["type"]["families"].items():
        common.append((f"font-{fam}", val))
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "ui")
        for st in group.get("styles", []):
            common.append((f"type-{st['name']}",
                           f"{st['fontWeight']} {st['fontSize']}/{st['lineHeight']} "
                           f"var(--amaya-font-{fam})"))
    for section in ("spacing", "radius", "layout"):
        for t in tokens[section]["tokens"]:
            common.append((t["name"], t["value"]))
    for section in ("color", "shadow"):
        for t in tokens[section]["tokens"]:
            v = t["value"]
            if isinstance(v, dict):
                light.append((t["name"], v["light"]))
                dark.append((t["name"], v["dark"]))
            else:
                common.append((t["name"], v))
    common += MOTION

    def block(items, indent="  "):
        return "\n".join(f"{indent}--amaya-{n}: {v};" for n, v in items)

    return (
        "/* GENERATED by ui/tools/gen-tokens.py from ui/design/tokens.json. Do not edit. */\n"
        "/* Every design token as --amaya-<name>. Light by default, dark via the\n"
        "   system/browser colour scheme. Durations drop to 0ms under reduced motion. */\n"
        f":root {{\n{block(common)}\n{block(light)}\n}}\n\n"
        f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{block(dark, '    ')}\n  }}\n}}\n\n"
        # An explicit theme wins over the media query (pages under Uniform
        # fingerprinting always see a light colour scheme).
        f":root[data-theme=\"dark\"] {{\n{block(dark)}\n}}\n\n"
        "@media (prefers-reduced-motion: reduce) {\n  :root {\n"
        "    --amaya-dur-hover: 0ms;\n    --amaya-dur-popover: 0ms;\n    --amaya-dur-sidebar: 0ms;\n"
        "  }\n}\n"
    )


def main():
    out = render(json.loads((UI / "design" / "tokens.json").read_text()))
    dest = UI / "tokens.css"
    if "--check" in sys.argv:
        sys.exit(0 if dest.is_file() and dest.read_text() == out else 1)
    dest.write_text(out)
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
